"""Minimal Django settings for CATMAID skeleton ingestion jobs.

The web container continues to use ``mysite.settings`` generated by CATMAID's
platform entrypoint. Ingestion tasks need the CATMAID models and controls but
must not run migrations, collect static files, create users, or start web
processes, so they use this small settings module instead.
"""

from __future__ import annotations

import os

from mysite.settings_base import *  # noqa: F403


def _required_environment(name: str) -> str:
    value = os.environ.get(name)
    if value is None or not value.strip():
        raise RuntimeError(f"{name} is required for CATMAID skeleton ingestion")
    return value


DATABASES = {
    "default": {
        "ENGINE": "custom_postgresql_psycopg2",
        "ATOMIC_REQUESTS": True,
        "NAME": _required_environment("DB_NAME"),
        "USER": _required_environment("DB_USER"),
        "PASSWORD": _required_environment("DB_PASS"),
        "HOST": _required_environment("DB_HOST"),
        "PORT": os.environ.get("DB_PORT", "5432"),
        "CONN_MAX_AGE": 0,
    }
}

# This module never serves requests or signs externally visible values. A
# dedicated override remains available for deployments that require one.
SECRET_KEY = os.environ.get(
    "SKELETON_INGESTION_DJANGO_SECRET_KEY",
    "catmaid-skeleton-ingestion-job-only",
)

DEBUG = False
ALLOWED_HOSTS: list[str] = []
TIME_ZONE = os.environ.get("TZ", "UTC")

CATMAID_URL = "/"
MEDIA_ROOT = os.environ.get(
    "CATMAID_INGESTION_MEDIA_ROOT",
    "/tmp/catmaid-skeleton-ingestion-media",
)
MEDIA_URL = "/files/"
STATIC_URL = "/static/"
STATIC_ROOT = "/tmp/catmaid-skeleton-ingestion-static"
HDF5_STORAGE_PATH = "/tmp/catmaid-skeleton-ingestion-hdf5"
CATMAID_IMPORT_PATH = "/tmp/catmaid-skeleton-ingestion-import"

# Enable cached spatial retrieval and notifications for imported data.
NODE_LIST_MAXIMUM_COUNT = None
NODE_PROVIDERS = [("cached_msgpack_grid", {"enabled": True})]
SPATIAL_UPDATE_NOTIFICATIONS = True

# Keep CATMAID extensions enabled if a future base image ships any.
INSTALLED_APPS = INSTALLED_APPS + tuple(  # noqa: F405
    f"{app_name}.apps.{app_name.title()}Config"
    for app_name in INSTALLED_EXTENSIONS  # noqa: F405
)
